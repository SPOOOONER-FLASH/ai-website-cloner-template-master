param([string]$TrackedReport)
$ErrorActionPreference = 'Stop'
$migrationRoot = 'E:\WorkResources\migration'
$rows = @()
$movedBytes = [long]0
$movedFiles = [long]0
foreach ($planFile in @('plan-live.json','plan-offline.json')) {
  foreach ($entry in (Get-Content -LiteralPath "$migrationRoot\$planFile" -Raw | ConvertFrom-Json)) {
    $item = Get-Item -LiteralPath $entry.source -Force -ErrorAction SilentlyContinue
    $backupExists = Test-Path -LiteralPath ($entry.source + '.codex-moved-20261007')
    $state = 'pending'
    if (-not $item -and -not $backupExists) { $state = 'absent' }
    elseif ($item.LinkType -eq 'Junction' -and [IO.Path]::GetFullPath($item.Target) -eq $entry.destination) {
      $state = if ($backupExists) { 'pending-cleanup' } else { 'moved' }
    }
    $bytes = [long]0
    $files = [long]0
    # Count the exact complete-verification receipt used to authorize cleanup.
    $proof = $null
    $ownerFile = "$($entry.destination).codex-migration-owner.json"
    if (Test-Path -LiteralPath $ownerFile) {
      $owner = Get-Content -LiteralPath $ownerFile -Raw | ConvertFrom-Json
      if ($owner.cleanupAuthorized -and $owner.source -eq $entry.source -and
          $owner.destination -eq $entry.destination -and
          $owner.verification -match '^verify-[a-f0-9]{32}\.json$') {
        $proofFile = Join-Path $migrationRoot $owner.verification
        if (Test-Path -LiteralPath $proofFile) {
          $candidate = Get-Content -LiteralPath $proofFile -Raw | ConvertFrom-Json
          if ($candidate.sha256_verified -and $candidate.source -eq $entry.source -and
              $candidate.target -eq $entry.destination) { $proof = $candidate }
        }
      }
    }
    if ($proof) {
      $bytes = [long]$proof.bytes
      $files = [long]$proof.files
      if ($state -eq 'moved') { $movedBytes += $bytes; $movedFiles += $files }
    } elseif ($state -eq 'moved') {
      $state = 'pending-proof'
    }
    $rows += @{source=$entry.source;destination=$entry.destination;state=$state;verifiedBytes=$bytes;verifiedFiles=$files}
  }
}
$summary = @{
  measuredAt=(Get-Date).ToString('o')
  CFreeBytes=(Get-PSDrive C).Free
  EFreeBytes=(Get-PSDrive E).Free
  verifiedMovedBytes=$movedBytes
  verifiedMovedFiles=$movedFiles
  movedDirectories=@($rows | Where-Object state -EQ 'moved').Count
  pendingDirectories=@($rows | Where-Object state -Like 'pending*').Count
  rows=$rows
}
$summary | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath "$migrationRoot\summary.json" -Encoding utf8
$lines = @(
  '# C to E work-resource migration',
  '',
  "Measured: $($summary.measuredAt)",
  '',
  "Verified resources physically moved and C originals removed: $([math]::Round($movedBytes / 1GB,3)) GiB, $movedFiles files.",
  "C free: $([math]::Round($summary.CFreeBytes / 1GB,2)) GiB. E free: $([math]::Round($summary.EFreeBytes / 1GB,2)) GiB.",
  "Moved directories: $($summary.movedDirectories). Pending directories: $($summary.pendingDirectories).",
  '',
  $(if ($summary.pendingDirectories) { 'This is a measured snapshot. Running Codex/Claude prevents the remaining app-state and main-checkout cutover.' } else { 'All planned current directories are on E with working compatibility aliases; no migration rerun is needed.' }),
  $(if ($summary.pendingDirectories) { 'Close both applications, then double-click E:\WorkResources\migration\Finish-Migration.cmd. Success is explicitly printed; failures preserve originals and name the pending paths.' } else { 'Migration completed. Keep the E directories and compatibility aliases in place.' }),
  'The finisher installs CODEX_HOME and developer TEMP/cache variables only after all mandatory mappings pass. Restart Windows once afterward.',
  'Microsoft Store installation files remain managed by Windows Settings; WindowsApps is not manually moved.',
  '',
  'Generated by scripts/windows/storage-migration/Report-Migration.ps1. Re-run this generator for fresh measurements.',
  '',
  '| State | C source | E destination | Verified GiB |',
  '|---|---|---|---|'
)
foreach ($row in $rows) {
  $lines += "| $($row.state) | $($row.source) | $($row.destination) | $([math]::Round($row.verifiedBytes/1GB,3)) |"
}
$lines | Set-Content -LiteralPath "$migrationRoot\STATUS.md" -Encoding utf8
if ($TrackedReport) { $lines | Set-Content -LiteralPath $TrackedReport -Encoding utf8 }
Write-Host "Verified moved: $([math]::Round($movedBytes/1GB,3)) GiB / $movedFiles files. C free: $([math]::Round($summary.CFreeBytes/1GB,2)) GiB. Pending: $($summary.pendingDirectories)."
