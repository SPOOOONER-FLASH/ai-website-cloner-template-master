#!/usr/bin/env node
/**
 * How much of the HYDE site would break in right-to-left: node scripts/audit-rtl-readiness.mjs
 *
 * Arabic is on the language list (docs/collaboration/2026-09-24-language-expansion-prep.md).
 * RTL does not mirror a layout by itself: every PHYSICAL direction utility (ml-, pr-, left-,
 * text-right, border-l, rounded-r …) keeps pointing the same way, so the page comes out
 * half-mirrored. Tailwind has LOGICAL equivalents (ms-, pe-, start-, text-end, border-s,
 * rounded-e …) that flip with `dir="rtl"`. This counts what would need converting, per
 * utility and per file, so the Arabic engineering estimate is a number and not a guess.
 *
 * Writes docs/research/RTL-READINESS.md. The RAYEN lane is skipped.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { laneOf } from "./lib/site-lanes.mjs";

const OUT = "docs/research/RTL-READINESS.md";
/** physical utility → logical replacement */
const MAP = [
  [/\b-?ml-/, "ms-"], [/\b-?mr-/, "me-"], [/\bpl-/, "ps-"], [/\bpr-/, "pe-"],
  [/\b-?left-/, "start-"], [/\b-?right-/, "end-"],
  [/\btext-left\b/, "text-start"], [/\btext-right\b/, "text-end"],
  [/\bborder-l\b|\bborder-l-/, "border-s"], [/\bborder-r\b|\bborder-r-/, "border-e"],
  [/\brounded-l\b|\brounded-l-/, "rounded-s"], [/\brounded-r\b|\brounded-r-/, "rounded-e"],
  [/\brounded-(tl|bl)\b|\brounded-(tl|bl)-/, "rounded-ss / rounded-es"],
  [/\brounded-(tr|br)\b|\brounded-(tr|br)-/, "rounded-se / rounded-ee"],
  [/\bfloat-left\b/, "float-start"], [/\bfloat-right\b/, "float-end"],
  [/\b-?translate-x-/, "(needs rtl: variant)"], [/\bspace-x-/, "(ok with rtl:space-x-reverse)"],
];

function files(dir) {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n).replace(/\\/g, "/");
    if (/node_modules|\/generated\//.test(p)) return [];
    if (statSync(p).isDirectory()) return files(p);
    return /\.(tsx|ts|css)$/.test(n) && laneOf(p) !== "rayen" ? [p] : [];
  });
}

const byUtility = new Map();
const byFile = new Map();
let total = 0;
/** CSS (modules and globals): physical properties → logical ones. */
const CSS = [
  [/\bmargin-left\s*:/g, "margin-left → margin-inline-start"],
  [/\bmargin-right\s*:/g, "margin-right → margin-inline-end"],
  [/\bpadding-left\s*:/g, "padding-left → padding-inline-start"],
  [/\bpadding-right\s*:/g, "padding-right → padding-inline-end"],
  [/(?<![\w-])left\s*:/g, "left: → inset-inline-start:"],
  [/(?<![\w-])right\s*:/g, "right: → inset-inline-end:"],
  [/\btext-align\s*:\s*(left|right)\b/g, "text-align: left/right → start/end"],
  [/\bborder-(left|right)(-\w+)?\s*:/g, "border-left/right → border-inline-start/end"],
  [/\bfloat\s*:\s*(left|right)\b/g, "float: left/right → inline-start/end"],
];

for (const f of files("src")) {
  const text = readFileSync(f, "utf8");
  if (f.endsWith(".css")) {
    for (const [re, key] of CSS) {
      const n = (text.match(re) ?? []).length;
      if (!n) continue;
      byUtility.set(key, (byUtility.get(key) ?? 0) + n);
      byFile.set(f, (byFile.get(f) ?? 0) + n);
      total += n;
    }
    continue;
  }
  // class strings only: className="…", cn(…), and @apply lines
  const chunks = [...text.matchAll(/className=\{?[`"']([^`"']+)[`"']|cn\(([^)]*)\)|@apply ([^;]+);/g)].map((m) => m.slice(1).join(" "));
  for (const chunk of chunks) {
    for (const token of chunk.split(/\s+/)) {
      const bare = token.replace(/^[\w-]+:/g, ""); // drop sm:, hover: … prefixes
      const hit = MAP.find(([re]) => re.test(bare) && new RegExp(`^${re.source}`).test(bare));
      if (!hit) continue;
      const key = `${bare.replace(/\d.*$|\[.*$/, "")} → ${hit[1]}`;
      byUtility.set(key, (byUtility.get(key) ?? 0) + 1);
      byFile.set(f, (byFile.get(f) ?? 0) + 1);
      total++;
    }
  }
}

const out = [
  "# RTL readiness (Arabic)",
  "",
  `Generated by \`scripts/audit-rtl-readiness.mjs\` on ${new Date().toISOString().slice(0, 10)}. Re-run after any layout work.`,
  "",
  `**${total} physical-direction utilities in ${byFile.size} files** would point the wrong way under \`dir="rtl"\`.`,
  "Most convert one-for-one to the logical utility on the right; `translate-x` and carousel/arrow",
  "logic need an `rtl:` variant or a mirrored value. Product photographs are never mirrored (a",
  "mirrored photo turns a left-hand door into a right-hand one).",
  "",
  "## By utility",
  "",
  "| Utility | Count |",
  "|---|---|",
  ...[...byUtility].sort((a, b) => b[1] - a[1]).map(([k, n]) => `| \`${k}\` | ${n} |`),
  "",
  "## Files with the most",
  "",
  "| File | Count |",
  "|---|---|",
  ...[...byFile].sort((a, b) => b[1] - a[1]).slice(0, 25).map(([k, n]) => `| \`${k}\` | ${n} |`),
  "",
];
writeFileSync(OUT, out.join("\n"));
console.log(`✓ ${OUT}: ${total} utilities in ${byFile.size} files`);
