#!/usr/bin/env node
/**
 * Writes src/app/<code>/ for every overlay locale: one root layout and the 22 routes the
 * Portuguese tree has, each a thin wrapper around src/components/locale-pages/.
 *
 * Generated rather than hand-copied for the reason the Spanish and Portuguese trees taught
 * twice: 22 near-identical files per language, edited by hand, drift — a hreflang that named
 * the wrong language, a link that left the tree. Here the template is the only place the
 * shape lives. Re-run after changing it; the output is committed so the build does not
 * depend on this script, and `--check` in test:export refuses a hand edit.
 *
 *   node scripts/scaffold-locale-routes.mjs           write
 *   node scripts/scaffold-locale-routes.mjs --check   fail if anything would change
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const LOCALES = ["fr", "de", "ja", "ko", "tr", "ru", "ar"];
const check = process.argv.includes("--check");

/** Static pages: dir → component module, component, metadata builder. */
const STATIC = [
  ["", "HomePage", "HomePage", "homeMetadata"],
  ["certifications", "CertificationsPage", "CertificationsPage", "certificationsMetadata"],
  ["company", "SimplePages", "CompanyPage", "companyMetadata"],
  ["configurator", "ConfiguratorPage", "ConfiguratorPage", "configuratorMetadata"],
  ["contact", "ContactPage", "ContactPage", "contactMetadata"],
  ["documents", "DocumentsPage", "DocumentsPage", "documentsMetadata"],
  ["downloads", "DownloadsPage", "DownloadsPage", "downloadsMetadata"],
  ["faq", "FaqPage", "FaqPage", "faqMetadata"],
  ["finishes", "FinishesPage", "FinishesPage", "finishesMetadata"],
  ["glossary", "GlossaryPage", "GlossaryPage", "glossaryMetadata"],
  ["guides", "ArticlePages", "GuidesIndexPage", "guidesIndexMetadata"],
  ["model-lookup", "ModelLookupPage", "ModelLookupPage", "modelLookupMetadata"],
  ["news", "ArticlePages", "NewsIndexPage", "newsIndexMetadata"],
  ["product-finder", "ProductFinderPage", "ProductFinderPage", "productFinderMetadata"],
  ["product-studies", "SimplePages", "ProductStudiesPage", "productStudiesMetadata"],
  ["products", "ProductsIndexPage", "ProductsIndexPage", "productsIndexMetadata"],
  ["products/argentina-ar4", "ArgentinaAr4Page", "ArgentinaAr4Page", "argentinaAr4Metadata"],
  ["projects", "ProjectPages", "ProjectsIndexPage", "projectsIndexMetadata"],
  ["services", "SimplePages", "ServicesPage", "servicesMetadata"],
];

/** Dynamic pages: dir → module, component, metadata builder, params builder, param names. */
const DYNAMIC = [
  ["collections/[collection]", "CollectionPage", "CollectionPage", "collectionMetadata", "collectionParams", ["collection"]],
  ["compare/[category]", "ComparePage", "ComparePage", "compareMetadata", "compareParams", ["category"]],
  ["guides/[slug]", "ArticlePages", "GuideArticlePage", "guideArticleMetadata", "guideParams", ["slug"]],
  ["news/[slug]", "ArticlePages", "NewsArticlePage", "newsArticleMetadata", "newsParams", ["slug"]],
  ["products/[category]", "CategoryPage", "CategoryPage", "categoryMetadata", "categoryParams", ["category"]],
  ["products/[category]/[slug]", "ProductPage", "ProductPage", "productMetadata", "productParams", ["category", "slug"]],
  ["projects/[slug]", "ProjectPages", "ProjectPage", "projectMetadata", "projectParams", ["slug"]],
];

const HEADER = "/** GENERATED by scripts/scaffold-locale-routes.mjs — edit the template there, not this file. */";

const layout = (code) => `import type { Metadata } from "next";
import { archivo } from "../fonts";
import "../globals.css";
import { SiteHeader } from "@/components/site/SiteHeader";
import { getMenuCategories } from "@/data/categories";
import { SiteFooter } from "@/components/site/SiteFooter";
import { LazyPromoDialog } from "@/components/site/LazyPromoDialog";
import { JsonLd, organisationSchema, websiteSchema } from "@/components/site/JsonLd";
import { Analytics, AnalyticsHead } from "@/components/site/Analytics";
import { absoluteUrl, defaultDescription, defaultTitle, indexable, siteName, siteUrl } from "@/data/site";
import { LOCALE_DIR, LOCALE_TAG, OG_LOCALE } from "@/lib/i18n";
import { alternateLanguages } from "@/lib/seo";
import { I18nClientBundle } from "@/data/generated/i18n-client/${code}";

${HEADER}
const LOCALE = "${code}" as const;

export const metadata: Metadata = {
  metadataBase: new URL(siteUrl),
  title: {
    default: defaultTitle[LOCALE],
    template: \`%s | \${siteName}\`,
  },
  description: defaultDescription[LOCALE],
  applicationName: siteName,
  alternates: {
    canonical: \`/\${LOCALE}/\`,
    languages: alternateLanguages("/"),
  },
  openGraph: {
    type: "website",
    siteName,
    locale: OG_LOCALE[LOCALE],
    url: absoluteUrl(\`/\${LOCALE}/\`),
    title: defaultTitle[LOCALE],
    description: defaultDescription[LOCALE],
    images: [
      {
        url: absoluteUrl("/images/editorial/home-panic-exit-bars.webp"),
        width: 2400,
        height: 943,
        alt: "HYDE",
      },
    ],
  },
  twitter: {
    card: "summary_large_image",
    title: defaultTitle[LOCALE],
    description: defaultDescription[LOCALE],
    images: [absoluteUrl("/images/editorial/home-panic-exit-bars.webp")],
  },
  robots: indexable
    ? { index: true, follow: true, googleBot: { index: true, follow: true, "max-image-preview": "large" } }
    : { index: false, follow: false },
};

export default function LocaleRootLayout({ children }: Readonly<{ children: React.ReactNode }>) {
  return (
    <html
      lang={LOCALE_TAG[LOCALE]}
      dir={LOCALE_DIR[LOCALE]}
      suppressHydrationWarning
      className={\`h-full antialiased \${archivo.variable}\`}
    >
      <head>
        <AnalyticsHead />
        <JsonLd data={organisationSchema()} />
        <JsonLd data={websiteSchema()} />
      </head>
      <body suppressHydrationWarning className="flex min-h-full flex-col">
        {/* This locale's client dictionary — one chunk, this locale only (src/lib/i18n-client.ts). */}
        <I18nClientBundle />
        <div className="flex min-h-screen flex-col justify-between">
          <SiteHeader categories={getMenuCategories()} />
          {children}
          <SiteFooter />
        </div>
        <LazyPromoDialog />
        <Analytics />
      </body>
    </html>
  );
}
`;

const staticPage = (code, [, mod, component, meta]) => `import type { Metadata } from "next";
import { ${component}, ${meta} } from "@/components/locale-pages/${mod}";

${HEADER}
export const metadata: Metadata = ${meta}("${code}");

export default function Page() {
  return <${component} locale="${code}" />;
}
`;

const dynamicPage = (code, [, mod, component, meta, params, names]) => {
  const type = names.map((n) => `${n}: string`).join("; ");
  const destructure = names.join(", ");
  const paramsCall = params === "guideParams" ? `${params}("${code}")` : `${params}()`;
  return `import type { Metadata } from "next";
import { ${component}, ${meta}, ${params} } from "@/components/locale-pages/${mod}";

${HEADER}
type Props = { params: Promise<{ ${type} }> };

export const dynamicParams = false;

export function generateStaticParams() {
  return ${paramsCall};
}

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { ${destructure} } = await params;
  return ${meta}("${code}", ${destructure});
}

export default async function Page({ params }: Props) {
  const { ${destructure} } = await params;
  return <${component} locale="${code}" ${names.map((n) => `${names.length === 1 ? "slug" : n}={${n}}`).join(" ")} />;
}
`;
};

let changed = 0;
const stale = [];
const expected = new Set();
const emit = (file, content) => {
  expected.add(file.replace(/\\/g, "/"));
  const current = existsSync(file) ? readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
  if (current === content) return;
  changed++;
  if (check) {
    stale.push(file);
    return;
  }
  mkdirSync(join(file, ".."), { recursive: true });
  writeFileSync(file, content);
};

for (const code of LOCALES) {
  const root = join("src", "app", code);
  emit(join(root, "layout.tsx"), layout(code));
  for (const entry of STATIC) emit(join(root, entry[0], "page.tsx"), staticPage(code, entry));
  for (const entry of DYNAMIC) emit(join(root, entry[0], "page.tsx"), dynamicPage(code, entry));

  /* Files in the tree that the template does not produce are leftovers from the seven-page era. */
  const walk = (dir) => {
    if (!existsSync(dir)) return;
    for (const item of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, item.name);
      if (item.isDirectory()) walk(full);
      else if (!expected.has(full.replace(/\\/g, "/"))) {
        changed++;
        if (check) stale.push(`${full} (unexpected)`);
        else rmSync(full);
      }
    }
  };
  walk(root);
}

if (check && changed) {
  for (const file of stale) console.error(`✗ stale: ${file}`);
  console.error(`${changed} generated route file(s) differ from the template. Run: node scripts/scaffold-locale-routes.mjs`);
  process.exit(1);
}
console.log(check ? "✓ locale routes match the template" : `✓ wrote locale routes (${changed} file(s) changed)`);
