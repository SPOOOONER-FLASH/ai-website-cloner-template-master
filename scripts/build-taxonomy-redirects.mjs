#!/usr/bin/env node
/**
 * Writes deploy/nginx/taxonomy-redirects.conf from content/taxonomy-moves.json.
 *
 * WHY A GENERATOR. The conf used to be hand-maintained next to a hardcoded table in
 * src/data/category-aliases.ts — the same fact in two places, which drifts the first time
 * somebody edits one and not the other. Drift here is expensive and silent: the app keeps
 * emitting its client-side stub while nginx starts 404ing the same URL, so the page looks
 * fine to anyone clicking through the site and dies for every crawler.
 *
 * WHY THE ORIGIN 301 MATTERS MORE THAN THE STUB. Under `output: "export"` Next cannot
 * emit a 301 — `permanentRedirect()` produces a client-side document. A crawler that does
 * not run JavaScript sees an empty page, and no ranking passes through it. These nginx
 * rules are the real redirect; the stub only covers in-app navigation.
 *
 * Both trailing-slash forms are emitted because Search Console has both indexed.
 *
 * Usage: node scripts/build-taxonomy-redirects.mjs [--check]
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const SOURCE = "content/taxonomy-moves.json";
const OUT = "deploy/nginx/taxonomy-redirects.conf";

const moves = JSON.parse(readFileSync(SOURCE, "utf8"));

const lines = [
  "# Cantonlock catalogue taxonomy redirects.",
  "#",
  `# Generated by scripts/build-taxonomy-redirects.mjs from ${SOURCE} — do not edit by hand.`,
  "#",
  "# Keep these as real HTTP redirects at the origin. The static export also ships",
  "# a browser-side Next redirect document for each retired path, but crawlers and",
  "# non-JavaScript clients should receive the canonical destination immediately.",
  "",
];

/** Both slash forms: Search Console has each of them indexed separately. */
function rule(from, to) {
  const bare = from.replace(/\/$/, "");
  return [
    `location = ${bare} {`,
    `    return 301 ${to};`,
    "}",
    "",
    `location = ${bare}/ {`,
    `    return 301 ${to};`,
    "}",
    "",
  ];
}

for (const [alias, { canonical, productSlugs }] of Object.entries(moves.categoryAliases)) {
  lines.push(`# Retired category: /products/${alias}/ -> /products/${canonical}/`);
  lines.push(...rule(`/products/${alias}`, `/products/${canonical}/`));
  for (const slug of productSlugs) {
    lines.push(
      ...rule(`/products/${alias}/${slug}`, `/products/${canonical}/${slug}/`),
    );
  }
}

for (const move of moves.productMoves) {
  lines.push(`# ${move.slug}: ${move.from} -> ${move.to}`);
  lines.push(
    ...rule(`/products/${move.from}/${move.slug}`, `/products/${move.to}/${move.slug}/`),
  );
}

const conf = lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== conf) {
    console.error(
      `${OUT} is out of date with ${SOURCE}.\nRun: node scripts/build-taxonomy-redirects.mjs`,
    );
    process.exit(1);
  }
  console.log(`${OUT} matches ${SOURCE}.`);
  process.exit(0);
}

mkdirSync("deploy/nginx", { recursive: true });
writeFileSync(OUT, conf);

const ruleCount = (conf.match(/return 301/g) ?? []).length;
console.log(
  `wrote ${OUT} — ${ruleCount} rules ` +
    `(${Object.keys(moves.categoryAliases).length} retired categories, ` +
    `${moves.productMoves.length} moved products)`,
);
console.log("⚠ nginx must be reloaded on the server for these to take effect.");
