#!/usr/bin/env node
/**
 * Writes deploy/nginx/taxonomy-redirects.conf from content/taxonomy-moves.json.
 *
 * WHY A GENERATOR. The conf used to be hand-maintained next to a hardcoded table in
 * src/data/category-aliases.ts — the same fact in two places, which drifts the first time
 * somebody edits one and not the other. Drift here is expensive and silent: the app keeps
 * emitting its client-side stub while nginx starts 404ing the same URL, so the page looks
 * fine to anyone clicking through the site and dies for every crawler.
 *
 * WHY THE ORIGIN 301 MATTERS MORE THAN THE STUB. Under `output: "export"` Next cannot
 * emit a 301 — `permanentRedirect()` produces a client-side document. A crawler that does
 * not run JavaScript sees an empty page, and no ranking passes through it. These nginx
 * rules are the real redirect; the stub only covers in-app navigation.
 *
 * Both trailing-slash forms are emitted because Search Console has both indexed.
 *
 * Usage: node scripts/build-taxonomy-redirects.mjs [--check]
 */

import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";

const SOURCE = "content/taxonomy-moves.json";
const OUT = "deploy/nginx/taxonomy-redirects.conf";
const EXPORT = "out";

const moves = JSON.parse(readFileSync(SOURCE, "utf8"));

/**
 * The locale mirrors, and why they get their own rules.
 *
 * ---------------------------------------------------------------------------
 * ⚠ THIS FILE EMITTED ENGLISH-ONLY RULES UNTIL 2026-09-17
 *
 * Search Console's 404 export of that date has two rows crawled days earlier:
 *
 *     https://cantonlock.com/es/products/panic-exit-devices/72-panic-exit-device/   09-12
 *     https://cantonlock.com/es/products/panic-exit-devices/030-panic-exit-device/  09-11
 *
 * Both are retired paths that the English side redirects correctly. The Spanish mirror
 * 404'd them, because every rule here began `/products/` and nothing carried the prefix.
 * Google had the Spanish URLs indexed — they are in the export — so a rename that was
 * handled cleanly in one tree dropped two indexed pages in another.
 *
 * Portuguese shipped on 2026-09-16 and would have inherited the same hole.
 *
 * ---------------------------------------------------------------------------
 * WHY THE DESTINATION IS VERIFIED AND NOT ASSUMED
 *
 * A redirect to a page that does not exist is worse than the 404 it replaces: it spends
 * the crawler's budget and lands on a soft error instead of a hard one. The mirrors are
 * not identical — Portuguese excludes /products/argentina-ar4, and a mirror can lag a
 * rename by a build — so each rule is checked against the EXPORT before it is written.
 * A destination that is not there is skipped and named in the run's output.
 */
const LOCALES = ["en", "es", "pt"];

/** The URL prefix for a locale, and where its pages live in the export. */
const prefixFor = (locale) => (locale === "en" ? "" : `/${locale}`);

/**
 * True when this path is a real page in the export.
 *
 * Checked against `out/` rather than against the catalogue data because the question is
 * whether the SERVER will have something to serve, and that is decided by what was
 * built. When the export is absent — a fresh checkout that has never run a build — the
 * check cannot be made, and the generator says so rather than silently emitting rules
 * nobody verified.
 */
function existsInExport(path) {
  return existsSync(`${EXPORT}${path}index.html`);
}

const hasExport = existsSync(EXPORT);
const skipped = [];

const lines = [
  "# Cantonlock catalog taxonomy redirects.",
  "#",
  `# Generated by scripts/build-taxonomy-redirects.mjs from ${SOURCE} — do not edit by hand.`,
  "#",
  "# Keep these as real HTTP redirects at the origin. The static export also ships",
  "# a browser-side Next redirect document for each retired path, but crawlers and",
  "# non-JavaScript clients should receive the canonical destination immediately.",
  "",
];

/**
 * Both slash forms, in every locale whose destination exists.
 *
 * Search Console has each slash form indexed separately, and since 2026-09-17 each locale
 * separately too — see the note at the top of this file.
 */
function rule(from, to) {
  const out = [];
  for (const locale of LOCALES) {
    const prefix = prefixFor(locale);
    const target = `${prefix}${to}`;
    if (hasExport && !existsInExport(target)) {
      skipped.push(`${prefix}${from} -> ${target} (destination not in the export)`);
      continue;
    }
    const bare = `${prefix}${from}`.replace(/\/$/, "");
    out.push(
      `location = ${bare} {`,
      `    return 301 ${target};`,
      "}",
      "",
      `location = ${bare}/ {`,
      `    return 301 ${target};`,
      "}",
      "",
    );
  }
  return out;
}

for (const [alias, { canonical, productSlugs }] of Object.entries(moves.categoryAliases)) {
  lines.push(`# Retired category: /products/${alias}/ -> /products/${canonical}/`);
  lines.push(...rule(`/products/${alias}`, `/products/${canonical}/`));
  for (const slug of productSlugs) {
    lines.push(
      ...rule(`/products/${alias}/${slug}`, `/products/${canonical}/${slug}/`),
    );
  }
}

for (const move of moves.productMoves) {
  lines.push(`# ${move.slug}: ${move.from} -> ${move.to}`);
  lines.push(
    ...rule(`/products/${move.from}/${move.slug}`, `/products/${move.to}/${move.slug}/`),
  );
}

/*
  Merged duplicates: one product, two records, one of them retired. The redirect stays
  inside the category — unlike a move, nothing changed category; the page simply should
  not have existed twice.
*/
for (const merge of moves.productMerges ?? []) {
  const dest = merge.toCategory ?? merge.category; // renamed AND moved: still one hop
  lines.push(`# merged duplicate: ${merge.from} -> ${merge.to}`);
  lines.push(
    ...rule(`/products/${merge.category}/${merge.from}`, `/products/${dest}/${merge.to}/`),
  );
}

/*
  Renamed product videos. rename-product-slug.mjs renames the .mp4 with the slug, so every
  rename also retires a video URL — and those are indexed separately (Google video results,
  AI crawlers). Cloudflare's AI crawler report for 2026-09-25 showed bots still requesting
  /videos/products/026-panic-exit-device.mp4 and two others from the 09-10 renames, all 404.
  One exact-match rule per file, no locale prefix (videos live at the root), and only when
  the destination file is really in the export.
*/
const VIDEO_DIR = "public/videos/products";
const videoFiles = existsSync(VIDEO_DIR) ? readdirSync(VIDEO_DIR) : [];
const videoRules = [];
for (const merge of moves.productMerges ?? []) {
  for (const file of videoFiles) {
    if (!file.startsWith(`${merge.to}.`)) continue;
    const old = merge.from + file.slice(merge.to.length);
    if (videoFiles.includes(old)) continue;
    const target = `/videos/products/${file}`;
    if (hasExport && !existsSync(`${EXPORT}${target}`)) {
      skipped.push(`/videos/products/${old} -> ${target} (video not in the export)`);
      continue;
    }
    videoRules.push(`location = /videos/products/${old} {`, `    return 301 ${target};`, "}", "");
  }
}
if (videoRules.length) lines.push("# Renamed product videos", ...videoRules);

const conf = lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== conf) {
    console.error(
      `${OUT} is out of date with ${SOURCE}.\nRun: node scripts/build-taxonomy-redirects.mjs`,
    );
    process.exit(1);
  }
  console.log(`${OUT} matches ${SOURCE}.`);
  process.exit(0);
}

mkdirSync("deploy/nginx", { recursive: true });
writeFileSync(OUT, conf);

const ruleCount = (conf.match(/return 301/g) ?? []).length;
if (!hasExport) {
  console.log(
    "⚠ out/ is not present, so no destination could be verified. " +
      "Run a build and regenerate before installing these on the server.",
  );
}
if (skipped.length) {
  console.log(`\n⚠ ${skipped.length} rule(s) NOT written, destination missing:`);
  for (const note of skipped) console.log(`    ${note}`);
  console.log(
    "  A redirect to a page that does not exist is worse than the 404 it replaces.\n",
  );
}

console.log(
  `wrote ${OUT} — ${ruleCount} rules ` +
    `(${Object.keys(moves.categoryAliases).length} retired categories, ` +
    `${moves.productMoves.length} moved products, ` +
    `${(moves.productMerges ?? []).length} merged duplicates)`,
);
console.log("⚠ nginx must be reloaded on the server for these to take effect.");
