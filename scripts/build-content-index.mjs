/**
 * Generates the barrel files that import every content JSON.
 *
 * Next has no equivalent of Vite's `import.meta.glob`, and a static export cannot read
 * the filesystem at request time. So the set of content files has to be expressed as
 * explicit imports — which is exactly the kind of list that goes stale when someone
 * adds a product through the CMS and forgets.
 *
 * It cannot go stale here: this runs from the `prebuild` npm hook, so every build
 * regenerates it from whatever is actually on disk.
 *
 *   node scripts/build-content-index.mjs
 */
import { readdirSync, writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

const GENERATED_DIR = "src/data/generated";
mkdirSync(GENERATED_DIR, { recursive: true });

const BANNER = `// GENERATED FILE — do not edit by hand.
// Regenerated by scripts/build-content-index.mjs on every build (npm prebuild).
// Edit the JSON in content/ instead, or use the CMS at /admin.
`;

/** Build one barrel for a folder collection. */
function barrel({ dir, type, typeImport, exportName, outFile }) {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort();

  const imports = files
    .map((f, i) => `import item${i} from "../../../${dir}/${f}";`)
    .join("\n");

  const list = files.map((_, i) => `item${i}`).join(", ");

  // JSON imports widen string-literal unions (e.g. Project["referenceStatus"]) to plain
  // `string`, so a direct annotation fails. The shape is still enforced — by the CMS
  // schema on write, and by every consumer of the exported type on read.
  writeFileSync(
    join(GENERATED_DIR, outFile),
    `${BANNER}${typeImport}\n${imports}\n\nexport const ${exportName} = [${list}] as unknown as ${type}[];\n`,
  );

  return files.length;
}

const productCount = barrel({
  dir: "content/products",
  type: "Product",
  typeImport: `import type { Product } from "../types";`,
  exportName: "products",
  outFile: "products.ts",
});

const projectCount = barrel({
  dir: "content/projects",
  type: "Project",
  typeImport: `import type { Project } from "../types";`,
  exportName: "projects",
  outFile: "projects.ts",
});

// Sanity check: every product slug must match its filename, otherwise the URL and the
// file drift apart and the CMS starts editing the wrong record.
const mismatched = readdirSync("content/products")
  .filter((f) => f.endsWith(".json"))
  .filter((f) => {
    const data = JSON.parse(readFileSync(join("content/products", f), "utf8"));
    return `${data.slug}.json` !== f;
  });

if (mismatched.length) {
  console.error(`\n❌ slug/filename mismatch in: ${mismatched.join(", ")}`);
  console.error("   Rename the file to match its slug, or fix the slug.");
  process.exit(1);
}

console.log(`content index: ${productCount} products, ${projectCount} projects`);
