#!/usr/bin/env node
/**
 * Writes src/app/<code>/ for every market locale: one layout and seven thin pages.
 *
 * The pages are generated rather than hand-copied because they are identical apart from
 * the locale string — and the Spanish and Portuguese trees have shown, twice, what happens
 * when twenty-two near-identical route files are edited by hand (a hreflang that named the
 * wrong language, a link that left the tree). Re-run after changing the template; the
 * output is committed so the build does not depend on this script.
 *
 *   node scripts/scaffold-market-routes.mjs           write
 *   node scripts/scaffold-market-routes.mjs --check   fail if anything would change
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const LOCALES = ["fr", "de", "ja", "ko", "tr", "ru", "ar"];
const PAGES = [
  { path: "/", dir: "", component: "MarketHome", name: "Home" },
  { path: "/products", dir: "products", component: "MarketProducts", name: "Products" },
  { path: "/company", dir: "company", component: "MarketCompany", name: "Company" },
  { path: "/services", dir: "services", component: "MarketServices", name: "Services" },
  { path: "/certifications", dir: "certifications", component: "MarketCertifications", name: "Certifications" },
  { path: "/faq", dir: "faq", component: "MarketFaq", name: "Faq" },
  { path: "/contact", dir: "contact", component: "MarketContact", name: "Contact" },
];
const check = process.argv.includes("--check");

const layout = (code) => `import type { Metadata } from "next";
import { archivo } from "../fonts";
import "../globals.css";
import { JsonLd, organisationSchema, websiteSchema } from "@/components/site/JsonLd";
import { Analytics, AnalyticsHead } from "@/components/site/Analytics";
import { indexable, siteName, siteUrl } from "@/data/site";
import { marketLocaleMeta } from "@/data/market-locales";
import { marketCopy, marketPageMetadata } from "@/lib/market";

/**
 * GENERATED by scripts/scaffold-market-routes.mjs — edit the template there, not this file.
 *
 * The ${code} market tree. One root layout per locale, like /es and /pt, because
 * <html lang> and dir are decided here and a shared root cannot express ten of them.
 */
const LOCALE = "${code}" as const;
const meta = marketLocaleMeta[LOCALE];

export const metadata: Metadata = {
  metadataBase: new URL(siteUrl),
  applicationName: siteName,
  ...marketPageMetadata(LOCALE, "/"),
  /* Page titles supply only their own name; the brand suffix is appended here. */
  title: {
    default: \`\${marketCopy[LOCALE].meta["/"].title} | \${siteName}\`,
    template: \`%s | \${siteName}\`,
  },
  robots: indexable
    ? { index: true, follow: true, googleBot: { index: true, follow: true, "max-image-preview": "large" } }
    : { index: false, follow: false },
};

export default function MarketRootLayout({ children }: Readonly<{ children: React.ReactNode }>) {
  return (
    <html
      lang={meta.htmlLang}
      dir={meta.dir}
      suppressHydrationWarning
      className={\`h-full antialiased \${archivo.variable}\`}
    >
      <head>
        <AnalyticsHead />
        <JsonLd data={organisationSchema()} />
        <JsonLd data={websiteSchema()} />
      </head>
      <body suppressHydrationWarning className="flex min-h-full flex-col">
        {/* Header and footer are rendered by each page (MarketMain), which knows which
            page it is; a layout cannot, and the language menu needs to. */}
        <div className="flex min-h-screen flex-col justify-between">{children}</div>
        <Analytics />
      </body>
    </html>
  );
}
`;

const page = (code, p) => `import type { Metadata } from "next";
import { ${p.component} } from "@/components/market/${p.component}";
import { marketPageMetadata } from "@/lib/market";

/** GENERATED by scripts/scaffold-market-routes.mjs — edit the template there. */
export const metadata: Metadata = marketPageMetadata("${code}", "${p.path}");

export default function Market${p.name}Page() {
  return <${p.component} locale="${code}" />;
}
`;

let changed = 0;
const emit = (file, content) => {
  const current = existsSync(file) ? readFileSync(file, "utf8") : null;
  // Compare line endings out: a Windows checkout (* text=auto) holds these as CRLF while the
  // template renders LF, and a byte compare called all 56 files stale (HYDE release, 2026-09-25).
  const lf = (s) => s.replace(/\r\n/g, "\n");
  if (current !== null && lf(current) === lf(content)) return;
  changed++;
  if (check) {
    console.error(`✗ stale: ${file}`);
    return;
  }
  mkdirSync(join(file, ".."), { recursive: true });
  writeFileSync(file, content);
};

for (const code of LOCALES) {
  const root = join("src", "app", code);
  emit(join(root, "layout.tsx"), layout(code));
  for (const p of PAGES) emit(join(root, p.dir, "page.tsx"), page(code, p));
}

if (check && changed) {
  console.error(`${changed} generated route file(s) differ from the template. Run: node scripts/scaffold-market-routes.mjs`);
  process.exit(1);
}
console.log(check ? "✓ market routes match the template" : `✓ wrote market routes (${changed} file(s) changed)`);
